// Package dnsfiles generates the resolver files a process in a profile sees
// (DESIGN.md §5).
package dnsfiles

import (
	"bufio"
	"fmt"
	"net/netip"
	"os"
	"path/filepath"
	"strings"
)

// ResolvConf renders a resolv.conf. With no servers it has no nameserver
// line: glibc then queries 127.0.0.1, the namespace's own loopback, and fails
// at once instead of leaking.
func ResolvConf(profile string, servers []netip.Addr, search []string) string {
	var b strings.Builder
	fmt.Fprintf(&b, "# Generated by vpncell for profile %q. Do not edit.\n", profile)
	if len(servers) == 0 {
		b.WriteString("# No DNS servers are configured or pushed for this profile.\n")
	}
	n := 0
	for _, s := range servers {
		if n == 3 { // glibc uses at most three
			break
		}
		fmt.Fprintf(&b, "nameserver %s\n", s)
		n++
	}
	if len(search) > 0 {
		fmt.Fprintf(&b, "search %s\n", strings.Join(search, " "))
	}
	b.WriteString("options edns0 trust-ad\n")
	return b.String()
}

// HostsLine is the nsswitch hosts line inside profiles: no mdns, no
// resolve (systemd-resolved over varlink/D-Bus), no mymachines.
const HostsLine = "hosts:          files myhostname dns"

// NsswitchConf copies the host file and rewrites only the hosts: line, so
// passwd/group sources (LDAP, SSSD) keep working.
func NsswitchConf(hostPath string) (string, error) {
	f, err := os.Open(hostPath)
	if err != nil {
		if os.IsNotExist(err) {
			return "passwd: files\ngroup: files\nshadow: files\n" + HostsLine + "\n", nil
		}
		return "", err
	}
	defer f.Close()
	var b strings.Builder
	b.WriteString("# Generated by vpncell from " + hostPath + "; only the hosts: line differs.\n")
	sc := bufio.NewScanner(f)
	seen := false
	for sc.Scan() {
		line := sc.Text()
		if strings.HasPrefix(strings.TrimSpace(line), "hosts:") {
			line = HostsLine
			seen = true
		}
		b.WriteString(line + "\n")
	}
	if err := sc.Err(); err != nil {
		return "", err
	}
	if !seen {
		b.WriteString(HostsLine + "\n")
	}
	return b.String(), nil
}

// WriteAtomic writes a file by rename, so bind-mounted directories see the
// new content at once.
func WriteAtomic(path, content string, mode os.FileMode) error {
	dir := filepath.Dir(path)
	tmp, err := os.CreateTemp(dir, ".tmp-*")
	if err != nil {
		return err
	}
	if _, err := tmp.WriteString(content); err != nil {
		tmp.Close()
		os.Remove(tmp.Name())
		return err
	}
	if err := tmp.Chmod(mode); err != nil {
		tmp.Close()
		os.Remove(tmp.Name())
		return err
	}
	if err := tmp.Close(); err != nil {
		os.Remove(tmp.Name())
		return err
	}
	if err := os.Rename(tmp.Name(), path); err != nil {
		os.Remove(tmp.Name())
		return err
	}
	return nil
}
